if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="EPMEM two-stage eval for Qwen-2.5-VL")

    # Model
    parser.add_argument("--model-path",  type=str, required=True,
                        help="HuggingFace model ID or local path "
                             "(e.g. Qwen/Qwen2.5-VL-7B-Instruct)")
    parser.add_argument("--model-base",  type=str, default=None)

    # Data
    parser.add_argument("--image-folder",         type=str, default="")
    parser.add_argument("--stage1_question_file", type=str, required=True)
    parser.add_argument("--stage1_answers_file",  type=str, required=True)
    parser.add_argument("--stage2_question_file", type=str, required=True)
    parser.add_argument("--stage2_answers_file",  type=str, required=True)

    # Chunked evaluation (multi-GPU sharding)
    parser.add_argument("--num-chunks",  type=int, default=1)
    parser.add_argument("--chunk-idx",   type=int, default=0)

    # Generation
    parser.add_argument("--temperature",    type=float, default=0.0)
    parser.add_argument("--top_p",          type=float, default=None)
    parser.add_argument("--num_beams",      type=int,   default=1)
    parser.add_argument("--max_new_tokens", type=int,   default=256)

    # EPMEM hyper-parameters
    parser.add_argument("--beta_mask", type=float, default=0.1,
                        help="Redundancy ratio β: fraction of low-relevance "
                             "image tokens to mask (0.1 = 10%%).")
    parser.add_argument("--beta_conf", type=float, default=0.12,
                        help="Confidence threshold α: if variance of A/B "
                             "probabilities < β_conf, keep full candidate set.")

    # Stage-2 input masking (independent of EFVR)
    parser.add_argument("--mask_input", action="store_true",
                        help="Zero out low-saliency image-token positions in the "
                             "model input during Stage 2.  The model attends only "
                             "to high-saliency patches.  Can be combined with "
                             "--use_efvr or used alone as an ablation.")

    # EFVR (Stage 2)
    parser.add_argument("--use_efvr", action="store_true",
                        help="Enable Emotion-Focused Visual Retracing in Stage 2.")
    parser.add_argument("--efvr_entropy_threshold", type=float, default=0.7,
                        help="Entropy threshold γ to trigger EFVR.")
    parser.add_argument("--efvr_retracing_ratio",   type=float, default=0.3,
                        help="Injection blend coefficient ρ.")
    parser.add_argument("--efvr_starting_layer",    type=int,   default=0,
                        help="Fallback range start (ignored if "
                             "--efvr_trigger_layers is set).")
    parser.add_argument("--efvr_ending_layer",      type=int,   default=20,
                        help="Fallback range end (ignored if "
                             "--efvr_trigger_layers is set).")
    parser.add_argument("--efvr_topk",              type=int,   default=10,
                        help="Top-K for entropy computation (currently fixed "
                             "to 10 inside the hook; this arg is parsed but "
                             "not forwarded).")
    parser.add_argument("--efvr_trigger_layers", type=int, nargs="+", default=None,
                        help="Explicit list of layer indices to monitor for "
                             "entropy (e.g. 12 13).  Overrides "
                             "--efvr_starting_layer / --efvr_ending_layer.")

    args = parser.parse_args()
    eval_model(args)
