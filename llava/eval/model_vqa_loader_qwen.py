def split_list(lst, n):
    chunk = math.ceil(len(lst) / n)
    return [lst[i: i + chunk] for i in range(0, len(lst), chunk)]


def get_chunk(lst, n, k):
    return split_list(lst, n)[k]


def build_qwen_inputs(
    processor: AutoProcessor,
    question_text: str,
    pil_image: Image.Image,
    device: str = "cuda",
) -> dict:
    """
    Format a single (image, text) pair for Qwen-2.5-VL using the chat template
    and return the processor outputs as CUDA tensors (batch_size=1).

    The user message content is:
        <|vision_start|><image_pad tokens><|vision_end|>
        {question_text}

    which the processor handles when we pass ``images=[pil_image]``.
    """
    messages = [
        {
            "role": "user",
            "content": [
                {"type": "image"},          # image placeholder
                {"type": "text", "text": question_text},
            ],
        }
    ]
    text = processor.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    inputs = processor(
        text=[text],
        images=[pil_image],
        return_tensors="pt",
        padding=True,
    )
    return {k: v.to(device) for k, v in inputs.items()}


# ─────────────────────────────────────────────────────────────────────────────
# Attention-map → mask_index   (Negative Saliency Mask, §3.3 of the paper)
# ─────────────────────────────────────────────────────────────────────────────

# The EEG prompt that appears at the start of every Stage-1 question.
# Must exactly match the text in stage_1.jsonl (note the typo "imege").
# _EEG_PROMPT = "Please focus on emotion."
_EEG_PROMPT = "Please focus on the main emotion conveyed by the image."



def compute_mask_index(
    hidden_states_tuple,            # tuple of [B, Q, H] per layer (output_hidden_states)
    input_ids: torch.Tensor,        # [1, L]  full prompt token IDs
    image_token_id: int,
    vision_end_token_id: int,
    eeg_token_ids: torch.Tensor,    # 1-D tensor of EEG prompt token IDs
    beta_mask: float,
    hs_layer: int = -1,             # which layer to use (-1 = last decoder layer)
    debug: bool = False,
) -> Optional[List[int]]:
    """
    Compute the Negative Saliency Mask indices using hidden-state cosine
    similarity as the saliency signal.

    Rationale
    ---------
    Qwen-2.5-VL uses PyTorch SDPA which does not expose per-head attention
    weights (output_attentions=True returns an empty tuple).  Instead we use
    the hidden states at the last decoder layer:

        saliency[j] = mean_{i in EEG} cosine_sim(h[eeg_i], h[img_j])

    Image tokens with LOW cosine similarity to the EEG prompt are semantically
    distant from the emotion query → good candidates for masking.

    Steps
    -----
    1. Identify image-token positions  (ids == image_token_id).
    2. Find EEG-prompt token positions (first match after <|vision_end|>).
    3. Extract hidden states for EEG and image positions.
    4. Compute cosine similarity → average over EEG tokens → saliency per image token.
    5. Return the β_mask fraction with the LOWEST saliency ("redundant" tokens).

    Returns None if EEG prompt cannot be located.
    """
    if hidden_states_tuple is None or len(hidden_states_tuple) == 0:
        return None

    ids = input_ids[0]   # [L]

    # ── 1. Image token positions ─────────────────────────────────────────────
    img_positions = (ids == image_token_id).nonzero(as_tuple=True)[0]  # [n_img]
    if len(img_positions) == 0:
        if debug:
            print("[mask] WARNING: no image tokens found in input_ids")
        return None
    n_img = len(img_positions)

    # ── 2. EEG-prompt token positions ────────────────────────────────────────
    # We identify the text that immediately follows the <|vision_end|> token;
    # the EEG prompt ("Please focus on the main emotion…") is always the first
    # sentence there.
    #
    # Strategy: first try an exact substring match so we skip any leading
    # punctuation tokens (newlines, spaces) that Qwen's chat template inserts.
    # If the exact match fails — which happens when the tokenizer merges a
    # leading '\n' with 'Please' into a single token in context — we fall back
    # to a fixed-length window starting just after vision_end.  In either case
    # we end up pointing at the EEG-prompt portion of the sequence.
    ve_positions = (ids == vision_end_token_id).nonzero(as_tuple=True)[0]
    search_start = (ve_positions[-1].item() + 1) if len(ve_positions) > 0 \
                   else (img_positions[-1].item() + 1)

    n_key    = len(eeg_token_ids)
    post_ids = ids[search_start:]

    # ── 2a. Exact match (tries offsets 0..5 to skip leading whitespace tokens)
    eeg_abs_positions = None
    for offset in range(min(6, len(post_ids))):
        window = post_ids[offset:]
        for i in range(len(window) - n_key + 1):
            if torch.equal(window[i: i + n_key], eeg_token_ids):
                eeg_abs_positions = list(range(search_start + offset + i,
                                               search_start + offset + i + n_key))
                break
        if eeg_abs_positions is not None:
            break

    # ── 2b. Fallback: fixed window after vision_end ───────────────────────────
    #    If exact match fails (e.g. because the tokenizer merged '\nPlease'
    #    into a single token in the chat-template context), we take the first
    #    n_key+2 tokens after vision_end.  The extra +2 accommodates one or two
    #    leading newline/space tokens that Qwen's template inserts.
    # 匹配的不是找不到原句 → 直接取 <|vision_end|> 后面一段固定区域当作 EEG 提示句
    if eeg_abs_positions is None:
        if debug:
            print("[mask] Exact EEG match failed; falling back to fixed "
                  f"window [{search_start}, {search_start + n_key + 2})")
        win_end = min(search_start + n_key + 2, len(ids))
        if win_end > search_start:
            eeg_abs_positions = list(range(search_start, win_end))
        else:
            if debug:
                print("[mask] WARNING: could not locate EEG region")
            return None

    # ── 3. Extract hidden states ──────────────────────────────────────────────
    hs = hidden_states_tuple[hs_layer]   # [B, Q, H]  (last decoder layer output)

    eeg_pos_t = torch.tensor(eeg_abs_positions, device=hs.device)
    img_pos_t = img_positions.to(hs.device)

    # Safety clamp
    q_len = hs.shape[1]
    eeg_pos_t = eeg_pos_t[eeg_pos_t < q_len]
    img_pos_t = img_pos_t[img_pos_t < q_len]

    if len(eeg_pos_t) == 0 or len(img_pos_t) == 0:
        return None

    eeg_hs = hs[:, eeg_pos_t, :]   # [B, n_eeg, H]
    img_hs = hs[:, img_pos_t, :]   # [B, n_img, H]

    # ── 4. Cosine similarity → per-image saliency ────────────────────────────
    eeg_norm = F.normalize(eeg_hs.float(), dim=-1)   # [B, n_eeg, H]
    img_norm = F.normalize(img_hs.float(), dim=-1)   # [B, n_img, H]

    # [B, n_eeg, n_img]
    sim = torch.bmm(eeg_norm, img_norm.transpose(1, 2))

    # Average over EEG tokens → [B, n_img]
    saliency = sim.mean(dim=1)

    if debug:
        print(f"[mask] n_img={n_img}  n_eeg={len(eeg_pos_t)}")
        print(f"[mask] saliency  min={saliency.min().item():.4f} "
              f"max={saliency.max().item():.4f}")

    # ── 5. Select β_mask fraction with LOWEST saliency ───────────────────────
    k = max(1, int(n_img * beta_mask))
    _, mask_idx_t = torch.topk(-saliency, k, dim=1)
    mask_index = mask_idx_t[0].tolist()

    if debug:
        print(f"[mask] k={k}  mask_index (first 5)={mask_index[:5]}")

    return mask_index


# ─────────────────────────────────────────────────────────────────────────────
# Main evaluation function
# ─────────────────────────────────────────────────────────────────────────────

def eval_model(args):
    # ── Load model & processor ───────────────────────────────────────────────
    print(f"Loading model from {args.model_path} ...")
    model = Qwen2_5_VLForEPMEM.from_pretrained(
        args.model_path,
        torch_dtype=torch.bfloat16,
        device_map="auto",
        low_cpu_mem_usage=True,
    )
    model.eval()

    # Use Qwen2_5_VLProcessor directly to bypass AutoProcessor's video-processor
    # auto-detection (which tries to fetch video_preprocessor_config.json from the
    # Hub and fails when the network is unavailable or the file is not cached).
    try:
        processor = Qwen2_5_VLProcessor.from_pretrained(
            args.model_path, local_files_only=True
        )
    except Exception:
        processor = AutoProcessor.from_pretrained(
            args.model_path, local_files_only=True
        )
    tokenizer = processor.tokenizer

    # ── Special token IDs ────────────────────────────────────────────────────
    image_token_id      = model.config.image_token_id
    vision_end_token_id = getattr(model.config, "vision_end_token_id",
                                  tokenizer.convert_tokens_to_ids("<|vision_end|>"))

    # Pre-tokenise the EEG prompt for matching in input_ids
    eeg_token_ids = torch.tensor(
        tokenizer.encode(_EEG_PROMPT, add_special_tokens=False),
        device="cuda",
    )
    print(f"EEG prompt token IDs (len={len(eeg_token_ids)}): {eeg_token_ids.tolist()}")

    is_first_sample = True     # for verbose debug on first sample

    # ═════════════════════════════════════════════════════════════════════════
    #  STAGE 1 — Emotion Perception Augmentation
    # ═════════════════════════════════════════════════════════════════════════
    questions = [json.loads(q)
                 for q in open(os.path.expanduser(args.stage1_question_file))]
    questions = get_chunk(questions, args.num_chunks, args.chunk_idx)

    os.makedirs(os.path.dirname(os.path.expanduser(args.stage1_answers_file)),
                exist_ok=True)
    ans_file = open(os.path.expanduser(args.stage1_answers_file), "w")

    # EFVR is OFF during Stage 1
    model.deactivate_efvr()

    for line in tqdm(questions, desc="Stage 1"):
        idx        = line["question_id"]
        image_file = line["image"]
        qs         = line["text"]

        # ── Build inputs ─────────────────────────────────────────────────────
        pil_image = Image.open(
            os.path.join(args.image_folder, image_file)
        ).convert("RGB")

        batch = build_qwen_inputs(processor, qs, pil_image, device="cuda")
        input_ids      = batch["input_ids"]
        attention_mask = batch["attention_mask"]
        pixel_values   = batch["pixel_values"].to(torch.bfloat16)
        image_grid_thw = batch.get("image_grid_thw", None)

        # ── Generate (Stage 1: returns hidden states from prefill forward) ────
        with torch.inference_mode():
            new_ids, token_logits, prefill_hs = model.generate(
                inputs=input_ids,
                pixel_values=pixel_values,
                image_grid_thw=image_grid_thw,
                attention_mask=attention_mask,
                do_sample=(args.temperature > 0),
                temperature=args.temperature if args.temperature > 0 else None,
                top_p=args.top_p,
                num_beams=args.num_beams,
                max_new_tokens=args.max_new_tokens,
                output_scores=True,
                return_dict_in_generate=True,
            )

        # ── Decode output text ───────────────────────────────────────────────
        outputs = tokenizer.batch_decode(new_ids, skip_special_tokens=True)[0].strip()

        # Normalise Stage-1 answer: the model may emit 'B.' / 'b.' / 'A.' etc.
        # stage1_to_2() does an exact match on 'A' or 'B', so we strip any
        # trailing punctuation and normalise to uppercase.
        if outputs and outputs[0].upper() in ('A', 'B'):
            outputs = outputs[0].upper()

        # ── Confidence-guided polarity decision  (β_conf, eq. 4) ─────────────
        #    token_logits[0]: [B, V]  — logits for the first generated token
        if token_logits:
            first_logit = token_logits[0]                             # [B, V]
            probs = F.softmax(first_logit[0], dim=-1)                 # [V]

            token_id_A = tokenizer("A", add_special_tokens=False).input_ids[0]
            token_id_B = tokenizer("B", add_special_tokens=False).input_ids[0]

            prob_A = probs[token_id_A].item()
            prob_B = probs[token_id_B].item()
            var_AB = torch.var(torch.tensor([prob_A, prob_B])).item()

            # If variance is below β_conf the model is uncertain →
            # keep full candidate set (output probability percentages)
            if var_AB < args.beta_conf:
                pos_pct = int(round(prob_A * 100))
                neg_pct = int(round(prob_B * 100))
                outputs = f"{pos_pct} {neg_pct}"
        else:
            var_AB = 0.0

        # ── Negative Saliency Mask  (β_mask, eqs. 5-6) ───────────────────────
        mask_index = compute_mask_index(
            hidden_states_tuple = prefill_hs,
            input_ids           = input_ids,
            image_token_id      = image_token_id,
            vision_end_token_id = vision_end_token_id,
            eeg_token_ids       = eeg_token_ids,
            beta_mask           = args.beta_mask,
            hs_layer            = -1,        # last decoder layer
            debug               = is_first_sample,
        )

        if is_first_sample:
            print(f"\n=== Stage-1 debug (first sample) ===")
            print(f"  outputs      : {repr(outputs)}")
            print(f"  var_AB       : {var_AB:.4f}  (β_conf={args.beta_conf})")
            print(f"  mask_index   : {mask_index}")
            if prefill_hs is not None and len(prefill_hs) > 0:
                print(f"  hidden_states tuple len : {len(prefill_hs)}")
                print(f"  last-layer shape        : {prefill_hs[-1].shape}")
            else:
                print(f"  hidden_states           : None or empty")
            print("=====================================\n")
            is_first_sample = False

        # ── Write Stage-1 answer ─────────────────────────────────────────────
        ans_file.write(json.dumps({
            "question_id": idx,
            "prompt":      qs,
            "text":        outputs,
            "answer_id":   shortuuid.uuid(),
            "mask_index":  mask_index,
            "model_id":    args.model_path,
            "var":         var_AB,
            "metadata":    {},
        }) + "\n")

    ans_file.close()
    print("Stage 1 complete.")

    # ═════════════════════════════════════════════════════════════════════════
    #  Stage 1 → Stage 2 question bridging
    # ═════════════════════════════════════════════════════════════════════════
    print("Building Stage-2 question file ...")
    stage1_to_2(
        args.stage1_answers_file,
        args.stage1_question_file,
        args.stage2_question_file,
    )

    # ═════════════════════════════════════════════════════════════════════════
    #  STAGE 2 — Memory-Refreshed Emotion Inference
    # ═════════════════════════════════════════════════════════════════════════
    questions2 = [json.loads(q)
                  for q in open(os.path.expanduser(args.stage2_question_file))]
    questions2 = get_chunk(questions2, args.num_chunks, args.chunk_idx)

    os.makedirs(os.path.dirname(os.path.expanduser(args.stage2_answers_file)),
                exist_ok=True)
    ans_file2 = open(os.path.expanduser(args.stage2_answers_file), "w")

    # ── Activate EFVR if requested ───────────────────────────────────────────
    if args.use_efvr:
        model.activate_efvr(
            entropy_threshold = args.efvr_entropy_threshold,
            retracing_ratio   = args.efvr_retracing_ratio,
            starting_layer    = args.efvr_starting_layer,
            ending_layer      = args.efvr_ending_layer,
            trigger_layers    = args.efvr_trigger_layers,   # list or None
        )
    else:
        model.deactivate_efvr()

    for line in tqdm(questions2, desc="Stage 2"):
        idx        = line["question_id"]
        image_file = line["image"]
        qs         = line["text"]

        # Retrieve mask_index that was saved in Stage 1
        current_mask_index = line.get("mask_index", None)
        if isinstance(current_mask_index, list) and len(current_mask_index) == 0:
            current_mask_index = None

        pil_image = Image.open(
            os.path.join(args.image_folder, image_file)
        ).convert("RGB")

        batch = build_qwen_inputs(processor, qs, pil_image, device="cuda")
        input_ids      = batch["input_ids"]
        attention_mask = batch["attention_mask"]
        pixel_values   = batch["pixel_values"].to(torch.bfloat16)
        image_grid_thw = batch.get("image_grid_thw", None)

        with torch.inference_mode():
            new_ids, _, _ = model.generate(
                inputs=input_ids,
                pixel_values=pixel_values,
                image_grid_thw=image_grid_thw,
                attention_mask=attention_mask,
                do_sample=(args.temperature > 0),
                temperature=args.temperature if args.temperature > 0 else None,
                top_p=args.top_p,
                num_beams=args.num_beams,
                max_new_tokens=args.max_new_tokens,
                output_scores=True,
                return_dict_in_generate=True,
                mask_index=current_mask_index,      # used by EFVR and/or mask_input
                mask_input=args.mask_input,         # zero-out low-saliency patches in input
            )

        outputs = tokenizer.batch_decode(new_ids, skip_special_tokens=True)[0].strip()

        ans_file2.write(json.dumps({
            "question_id": idx,
            "prompt":      qs,
            "text":        outputs,
            "answer_id":   shortuuid.uuid(),
            "model_id":    args.model_path,
            "metadata":    {},
        }) + "\n")

    ans_file2.close()
    print("Stage 2 complete.")


