"""beta_mask
Two-stage EPMEM evaluation pipeline for Qwen-2.5-VL.

Stage 1 — Emotion Perception Augmentation
  • Coarse Positive/Negative polarity classification
  • Confidence-guided candidate narrowing  (β_conf, equation 4 in the paper)
  • Negative Saliency Mask via attention from EEG-prompt tokens to image tokens
    (β_mask, equations 5-6)  →  writes stage1_answers_file with mask_index

Stage 2 — Memory-Refreshed Emotion Inference
  • ATC prompting (Analyze-Then-Choose)  generated by stage1_to_2()
  • Optionally activates EFVR (Emotion-Focused Visual Retracing) via
    --use_efvr flag  (equations 7-9 in the paper)
  • Reads mask_index from stage1_answers_file and passes to model.generate()

Usage
-----
python3 -m llava.eval.model_vqa_loader_qwen \
    --model-path Qwen/Qwen2.5-VL-7B-Instruct \
    --image-folder /path/to/images \
    --stage1_question_file  .../stage_1.jsonl \
    --stage1_answers_file   .../stage1_out.jsonl \
    --stage2_question_file  .../stage_2_mask0.1.jsonl \
    --stage2_answers_file   .../stage2_out.jsonl \
    --beta_mask 0.1  --beta_conf 0.12 \
    --use_efvr \
    --efvr_entropy_threshold 0.7 \
    --efvr_retracing_ratio   0.3 \
    --efvr_trigger_layers    12 13 \
    --temperature 0  --max_new_tokens 256
"""

